/**
 * CloudScale shared Telegram settings behaviour.
 *
 * Wires the card that CloudScale_Telegram::render_settings_fields() renders: the
 * Show/Hide toggles on the token and chat-id fields, Fetch Chat ID and Send Test.
 * The nonces travel as data attributes on the buttons and ajaxurl is the admin
 * global, so nothing is localised and the file carries no per-site data.
 *
 * This used to be a PHP string attached as inline script to a src-less handle.
 * WordPress.org read that as bypassing the enqueue API (28Aug26), and it is the
 * same shape whichever function prints it, so the behaviour now ships as an
 * asset and the PHP only enqueues it.
 *
 * DO NOT EDIT THIS FILE in individual plugin directories.
 * Edit shared-admin-ui/cloudscale-telegram.js and re-run the shared sync step.
 */
( function () {
    'use strict';

    // Re-runnable: cyber-devtools switches admin tabs client-side and dispatches
    // 'csdt:tab-shown' after swapping the DOM, so wiring captured at load could be
    // pointing at discarded nodes (see the contract note in cs-tab-router.js).
    // Each element is marked once it is wired, so re-running init over nodes that
    // survived the swap never binds a handler twice.
    var BOUND = 'csTelegramBound';

    function csTelegramInit() {
        [ 'cs-telegram-token', 'cs-telegram-chat-id' ].forEach( function ( inputId ) {
            var toggleId = inputId === 'cs-telegram-token' ? 'cs-telegram-token-toggle' : 'cs-telegram-chat-toggle';
            var inp = document.getElementById( inputId );
            var btn = document.getElementById( toggleId );
            if ( ! inp || ! btn || btn.dataset[ BOUND ] ) { return; }
            btn.dataset[ BOUND ] = '1';
            btn.addEventListener( 'click', function () {
                var shown = inp.type === 'text';
                inp.type = shown ? 'password' : 'text';
                btn.textContent = shown ? 'Show' : 'Hide';
            } );
        } );

        var fetchBtn = document.getElementById( 'cs-telegram-fetch-btn' );
        if ( fetchBtn && ! fetchBtn.dataset[ BOUND ] ) {
            fetchBtn.dataset[ BOUND ] = '1';
            fetchBtn.addEventListener( 'click', function () {
                var btn    = this;
                var token  = ( document.getElementById( 'cs-telegram-token' ).value || '' ).trim();
                var msg    = document.getElementById( 'cs-telegram-fetch-msg' );
                var chatIn = document.getElementById( 'cs-telegram-chat-id' );
                if ( ! token ) { msg.textContent = 'Enter bot token first.'; msg.style.color = '#c00'; return; }
                btn.disabled = true;
                msg.textContent = 'Fetching...'; msg.style.color = '#666';
                var fd = new FormData();
                fd.append( 'action', 'cloudscale_telegram_fetch_chat_id' );
                fd.append( 'nonce', btn.dataset.nonce );
                fd.append( 'telegram_token', token );
                fetch( ajaxurl, { method: 'POST', body: fd } )
                    .then( function ( r ) { return r.json(); } )
                    .then( function ( d ) {
                        if ( d.success ) { chatIn.value = d.data.chat_id; msg.textContent = 'Chat ID found: ' + d.data.chat_id; msg.style.color = '#0a5'; }
                        else { msg.textContent = d.data || 'Failed.'; msg.style.color = '#c00'; }
                    } )
                    .catch( function () { msg.textContent = 'Request error.'; msg.style.color = '#c00'; } )
                    .finally( function () { btn.disabled = false; } );
            } );
        }

        var testBtn = document.getElementById( 'cs-telegram-test-btn' );
        if ( testBtn && ! testBtn.dataset[ BOUND ] ) {
            testBtn.dataset[ BOUND ] = '1';
            testBtn.addEventListener( 'click', function () {
                var btn = this;
                var msg = document.getElementById( 'cs-telegram-test-msg' );
                btn.disabled = true;
                if ( msg ) { msg.textContent = 'Sending...'; msg.style.color = '#666'; }
                var fd = new FormData();
                fd.append( 'action', 'cloudscale_telegram_test' );
                fd.append( 'nonce', btn.dataset.nonce );
                fd.append( 'test_source', btn.dataset.source || '' );
                fetch( ajaxurl, { method: 'POST', body: fd } )
                    .then( function ( r ) { return r.json(); } )
                    .then( function ( d ) {
                        if ( msg ) { msg.textContent = d.success ? ( d.data && d.data.msg ? d.data.msg : 'Sent.' ) : ( d.data || 'Failed.' ); msg.style.color = d.success ? '#0a5' : '#c00'; }
                    } )
                    .catch( function () { if ( msg ) { msg.textContent = 'Request error.'; msg.style.color = '#c00'; } } )
                    .finally( function () { btn.disabled = false; } );
            } );
        }
    }

    csTelegramInit();
    document.addEventListener( 'csdt:tab-shown', csTelegramInit );
} )();
